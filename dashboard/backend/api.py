@app.get("/api/market", response_model=MarketDataResponse, tags=["Observability"])
async def get_market_data():
    """Returns recent OHLCV candles and computed technical indicator overlays."""
    service = BotService.get_instance()
    # If cache is empty, populate on-demand
    if not service.latest_candles:
        try:
            df = await service.bot.market_data.fetch_klines(
                symbol=service.config.symbol,
                interval=service.config.candle_interval,
                limit=100,
            )
            from bot.indicators import calculate_indicators
            enriched = calculate_indicators(df)
            candles_list = []
            for _, row in enriched.iterrows():
                from dashboard.backend.service import pd_isna
                candles_list.append({
                    "timestamp": int(row["timestamp"]),
                    "open": float(row["open"]),
                    "high": float(row["high"]),
                    "low": float(row["low"]),
                    "close": float(row["close"]),
                    "volume": float(row["volume"]),
                    "ema20": float(row["ema20"]) if "ema20" in row and not pd_isna(row["ema20"]) else None,
                    "ema50": float(row["ema50"]) if "ema50" in row and not pd_isna(row["ema50"]) else None,
                    "ema200": float(row["ema200"]) if "ema200" in row and not pd_isna(row["ema200"]) else None,
                    "rsi14": float(row["rsi14"]) if "rsi14" in row and not pd_isna(row["rsi14"]) else None,
                    "atr14": float(row["atr14"]) if "atr14" in row and not pd_isna(row["atr14"]) else None,
                    "volume_ratio": float(row["volume_ratio"]) if "volume_ratio" in row and not pd_isna(row["volume_ratio"]) else None,
                })
            service.latest_candles = candles_list
        except Exception as e:
            logger.warning(f"Failed to fetch initial candles: {e}")

    current_price = service.latest_candles[-1]["close"] if service.latest_candles else 0.0
    change_pct = 0.0
    if len(service.latest_candles) >= 2:
        prev = service.latest_candles[-2]["close"]
        if prev > 0:
            change_pct = (current_price - prev) / prev * 100.0

    return {
        "symbol": service.config.symbol,
        "interval": service.config.candle_interval,
        "current_price": current_price,
        "price_change_pct_5m": change_pct,
        "candles": service.latest_candles,
    }


