@app.websocket("/ws")
async def websocket_endpoint(websocket: WebSocket):
    """Real-time bi-directional streaming endpoint for dashboard telemetry."""
    service = BotService.get_instance()
    await service.ws_manager.connect(websocket)
    try:
        # Send initial state snapshot immediately upon connection
        await websocket.send_json({
            "type": "INITIAL_STATE",
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "status": service.get_status_dict(),
            "health": service.get_system_health_dict(),
            "logs": list(service.activity_logs)[:25],
        })
        while True:
            # Keep connection open and receive optional ping/pong or client messages
            msg = await websocket.receive_text()
            if msg == "ping":
                await websocket.send_json({"type": "pong", "timestamp": datetime.now(timezone.utc).isoformat()})
    except WebSocketDisconnect:
        service.ws_manager.disconnect(websocket)
    except Exception as e:
        logger.debug(f"WebSocket connection error: {e}")
        service.ws_manager.disconnect(websocket)


