@app.get("/api/trades", response_model=List[PaperTradeRecordSchema], tags=["Observability"])
def get_trades(
    symbol: Optional[str] = Query(None),
    win_only: Optional[bool] = Query(None),
    limit: int = Query(50, ge=1, le=500),
):
    """Returns closed paper trading history with optional filtering."""
    service = BotService.get_instance()
    trades = service.get_trades_list()
    
    if symbol:
        trades = [t for t in trades if t["symbol"] == symbol.upper()]
    if win_only is True:
        trades = [t for t in trades if t["is_winner"]]
    elif win_only is False:
        trades = [t for t in trades if not t["is_winner"]]

    return trades[:limit]


